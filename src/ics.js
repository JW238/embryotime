// iCalendar (.ics, RFC 5545) generation for a single experiment target event.
// Times are written in UTC ("Z" suffix), which every calendar app converts to the
// viewer's local zone correctly — no VTIMEZONE block needed.

import { formatDateTime, formatDuration } from './time.js';
import { displayName, eggCounts, formatReminder, formatTemperature, formatWindow, planSummary, plannedReturnOf, windowOf } from './experiment.js';
import { PLANNED_RETURN, formatHoursRange } from './hh-stages.js';

export const EVENT_LENGTH_MINUTES = 30;

/** 2026-10-27T17:20:00.000Z → 20261027T172000Z */
export function toIcsUtc(msOrIso) {
  return new Date(msOrIso).toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');
}

export function escapeIcsText(text) {
  return String(text ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r\n|\r|\n/g, '\\n');
}

/** Fold a content line to ≤75 octets (UTF-8), never splitting a multi-byte character. */
export function foldLine(line) {
  const encoder = new TextEncoder();
  const out = [];
  let current = '';
  let bytes = 0;
  for (const ch of line) {
    const len = encoder.encode(ch).length;
    const limit = out.length === 0 ? 75 : 74; // continuation lines start with a space
    if (bytes + len > limit) {
      out.push(current);
      current = '';
      bytes = 0;
    }
    current += ch;
    bytes += len;
  }
  out.push(current);
  return out.join('\r\n ');
}

/** Minutes before the event → negative ISO 8601 duration trigger. */
export function reminderTrigger(minutes) {
  if (minutes % 1440 === 0) return `-P${minutes / 1440}D`;
  if (minutes % 60 === 0) return `-PT${minutes / 60}H`;
  return `-PT${minutes}M`;
}

function eggLine(record) {
  const c = eggCounts(record);
  if (!c.known) return null;
  return c.active === c.initial ? `Eggs: ${c.initial}` : `Eggs: ${c.active} active of ${c.initial}`;
}

export function buildEventDescription(record) {
  const tz = record.timeZone;
  const lines = [
    `Experiment ID: ${record.experimentId}`,
    `Name: ${record.name}`,
    record.batchId && `Batch/sample ID: ${record.batchId}`,
    eggLine(record),
    `Target (lab return): ${formatDateTime(Date.parse(record.targetAt), tz)} [${tz}]`,
    `Placed in incubator: ${formatDateTime(Date.parse(record.placementAt), tz)}`,
    `Waiting duration: ${formatDuration(record.waitMinutes)}`,
    `Incubation at placement: ${formatDuration(record.currentIncubationMinutes)}`,
    `Projected total incubation at target: ${formatDuration(record.currentIncubationMinutes + record.waitMinutes)}`,
    record.conditions && `Conditions: ${record.conditions}`,
    record.notes && `Notes: ${record.notes}`,
  ];
  return `${lines.filter(Boolean).join('\n')}\n\nGenerated by EmbryoTime. Calculated schedule only — verify times before relying on them.`;
}

function windowDescription(record) {
  const tz = record.timeZone;
  const p = record.stagePlan;
  const w = windowOf(record);
  const ret = plannedReturnOf(record);
  const lines = [
    `Batch: ${displayName(record)} (record ${record.experimentId})`,
    eggLine(record),
    `ESTIMATED window for HH${p.targetStage} (not a guaranteed time): ${formatWindow(w, tz)} [${tz}]`,
    `Starting point: ${planSummary(p)}`,
    `Reference ages: starting age ${formatHoursRange(p.baselineAgeHours)}, HH${p.targetStage} ${formatHoursRange(p.targetAgeHours)}`,
    `Planned lab return: ${ret === null ? 'none chosen' : `${formatDateTime(ret, tz)} (${PLANNED_RETURN[p.plannedReturn].toLowerCase()})`}`,
    `Placed in incubator: ${formatDateTime(Date.parse(record.placementAt), tz)}`,
    record.temperature && `Incubation temperature: ${formatTemperature(record.temperature)} (estimates not adjusted for temperature)`,
    record.conditions && `Conditions: ${record.conditions}`,
    record.notes && `Notes: ${record.notes}`,
  ];
  return `${lines.filter(Boolean).join('\n')}\n\nEstimated from the Hamburger–Hamilton reference table (UNSW Embryology). HH stages are morphological and embryos develop at different rates. Generated by EmbryoTime.`;
}

function vevent({ uid, sequence, nowMs, start, end, summary, description, transparent, alarms }) {
  const lines = [
    'BEGIN:VEVENT',
    `UID:${uid}`,
    `SEQUENCE:${sequence}`,
    `DTSTAMP:${toIcsUtc(nowMs)}`,
    `DTSTART:${toIcsUtc(start)}`,
    `DTEND:${toIcsUtc(end)}`,
    `SUMMARY:${escapeIcsText(summary)}`,
    `DESCRIPTION:${escapeIcsText(description)}`,
    'STATUS:CONFIRMED',
    `TRANSP:${transparent ? 'TRANSPARENT' : 'OPAQUE'}`,
  ];
  for (const minutes of alarms ?? []) {
    lines.push(
      'BEGIN:VALARM',
      'ACTION:DISPLAY',
      `DESCRIPTION:${escapeIcsText(`${summary} — ${formatReminder(minutes)}`)}`,
      `TRIGGER:${reminderTrigger(minutes)}`,
      'END:VALARM'
    );
  }
  lines.push('END:VEVENT');
  return lines;
}

/**
 * Build the .ics text. UIDs are stable per experiment and SEQUENCE increases on each download,
 * so calendar apps that support updates can replace an earlier import.
 * Duration-based batches: one event at the target time (unchanged).
 * Stage-based batches: one event spanning the whole ESTIMATED window, plus a separate
 * "planned lab return" event only if the researcher chose one. Alerts attach to the planned
 * return if there is one, otherwise to the window's opening.
 */
export function buildIcs(record, { nowMs, sequence = record.calendar?.sequence ?? 0 }) {
  const head = ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//EmbryoTime//Incubation Scheduler//EN', 'CALSCALE:GREGORIAN', 'METHOD:PUBLISH'];
  const events = [];
  const w = windowOf(record);
  if (!w) {
    const start = Date.parse(record.targetAt);
    events.push(
      ...vevent({
        uid: `${record.uid}@embryotime.local`,
        sequence,
        nowMs,
        start,
        end: start + EVENT_LENGTH_MINUTES * 60_000,
        summary: `[${record.experimentId}] Lab return: ${record.name}`,
        description: buildEventDescription(record),
        alarms: record.reminderOffsets,
      })
    );
  } else {
    const ret = plannedReturnOf(record);
    const name = displayName(record);
    const description = windowDescription(record);
    events.push(
      ...vevent({
        uid: `${record.uid}-window@embryotime.local`,
        sequence,
        nowMs,
        start: w.startMs,
        end: Math.max(w.endMs, w.startMs + EVENT_LENGTH_MINUTES * 60_000),
        summary: `${name}: estimated HH${record.stagePlan.targetStage} window (estimate)`,
        description,
        transparent: true,
        alarms: ret === null ? record.reminderOffsets : [],
      })
    );
    if (ret !== null) {
      events.push(
        ...vevent({
          uid: `${record.uid}@embryotime.local`,
          sequence,
          nowMs,
          start: ret,
          end: ret + EVENT_LENGTH_MINUTES * 60_000,
          summary: `${name}: planned lab return`,
          description,
          alarms: record.reminderOffsets,
        })
      );
    }
  }
  return [...head, ...events, 'END:VCALENDAR'].map(foldLine).join('\r\n') + '\r\n';
}

export function icsFileName(record) {
  const safeId = record.experimentId.replace(/[^A-Za-z0-9._-]/g, '_');
  return `${safeId}-${toIcsUtc(record.targetAt).slice(0, 13)}Z.ics`;
}
